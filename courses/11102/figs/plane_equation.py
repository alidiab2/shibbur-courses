from _ch1lib import *

PLANE = [(40, 250), (350, 250), (450, 70), (140, 70)]


def lines_fig(items, title, alt, frames, h=None, size=21):
    n = len(items)
    f = Fig(480, h or (30 + 62 * n), alt=alt)
    for i, (t, c) in enumerate(items):
        f.chip(20, 14 + i * 62, 440, 50, t, c=c, solid=(i == n - 1 and c == "good"), size=size, step=i + 1)
    return f.block("", kind="steps", title=title, frames=frames)


def fig_param():
    f = Fig(480, 290, alt="مستوى في الفراغ: نقطة P0 ومتجهان v و u داخله، وأي نقطة في المستوى هي P0 + t v + s u")
    f.polygon(PLANE, c="mut", fill="soft")
    P0 = (120, 215)
    V = (250, 215); U = (170, 140)
    f.arrow(*P0, *V, c="1", w=5, step=2); f.text(V[0] + 6, V[1] + 30, "v", c="1", size=24, step=2)
    f.arrow(*P0, *U, c="2", w=5, step=2); f.text(U[0] - 28, U[1] - 2, "u", c="2", size=24, step=2)
    TV = (P0[0] + 1.5 * 130, 215)
    Pp = (TV[0] + 0.9 * 50, 215 - 0.9 * 75)
    f.line(*P0, *TV, c="1", w=4, dash=True, step=3)
    f.line(*TV, *Pp, c="2", w=4, dash=True, step=3)
    f.text(TV[0] - 40, TV[1] + 34, "t·v", c="1", size=21, step=3)
    f.text(TV[0] + 66, (TV[1] + Pp[1]) / 2 + 14, "s·u", c="2", size=21, step=3, anchor="left")
    f.dot(*Pp, c="good", r=10, step=4)
    f.text(450, Pp[1] - 30, "P₀ + t·v + s·u", c="good", size=20, step=4, anchor="right")
    f.dot(*P0, c="ink", r=9)
    f.text(P0[0] - 14, P0[1] + 34, "P₀", c="ink", size=22)
    return f.block("", kind="steps", title="الطريقة الأولى: الوصف المتجهي (פרמטרי)",
                   frames=["مستوى ونقطة \\(P_0\\) عليه", "متجهين \\(\\vec v,\\vec u\\) غير متناسبين داخل المستوى", "منمشي \\(t\\) مرة بـ \\(\\vec v\\) و \\(s\\) مرة بـ \\(\\vec u\\)", "كل نقطة بالمستوى بتطلع هيك"])


def fig_normal():
    f = Fig(480, 300, alt="مستوى فيه نقطة P0 والمتجه v عمودي عليه، ونقطة P أخرى والمتجه P0P داخل المستوى متعامد مع v")
    f.polygon(PLANE, c="mut", fill="soft")
    P0 = (170, 200); P = (340, 150)
    f.arrow(*P0, P0[0], 40, c="1", w=6, step=1); f.text(P0[0] + 14, 52, "v = (a,b,c)", c="1", size=22, step=1, anchor="left")
    f.dot(*P0, c="ink", r=9, step=1); f.text(P0[0] - 20, P0[1] + 32, "P₀", c="ink", size=22, step=1)
    f.arrow(*P0, *P, c="2", w=5, step=2)
    f.dot(*P, c="ink", r=9, step=2); f.text(P[0] + 14, P[1] + 30, "P", c="ink", size=22, step=2)
    f.line(P0[0], P0[1] - 22, P0[0] + 22, P0[1] - 22, c="ink", w=3, step=3)
    f.line(P0[0] + 22, P0[1] - 22, P0[0] + 22, P0[1], c="ink", w=3, step=3)
    f.text(250, 280, "P₀P · v = 0", c="good", size=24, step=3)
    return f.block("", kind="steps", title="الطريقة الثانية: الوصف الجبري",
                   frames=["نقطة \\(P_0\\) ومتجه \\(\\vec v\\) عمودي على المستوى", "أي نقطة \\(P\\) بالمستوى: المتجه \\(\\overrightarrow{P_0P}\\) داخل المستوى", "إذا وفقط إذا \\(\\overrightarrow{P_0P}\\) عمودي على \\(\\vec v\\): الضرب السلمي 0"])


def fig_notunique():
    f = Fig(480, 280, alt="ثلاث أسهم عمودية على نفس المستوى: الأول v والثاني 2v والثالث -v فكلها نورمال للمستوى")
    f.polygon(PLANE, c="mut", fill="soft")
    f.arrow(130, 190, 130, 90, c="1", w=5); f.text(144, 100, "v", c="1", size=24, anchor="left")
    f.arrow(250, 200, 250, 30, c="good", w=5); f.text(264, 50, "2v", c="good", size=24, anchor="left")
    f.arrow(370, 150, 370, 240, c="bad", w=5); f.text(384, 220, "−v", c="bad", size=24, anchor="left")
    return f.block("لاحظ: كلهم نورمال لنفس المستوى (نفس الخط، طول مختلف أو اتجاه معاكس).")


