          P("يعني \\(2\\vec v\\) و \\(-\\vec v\\) و \\(\\frac12\\vec v\\) كلهم بيعطوا نفس المستوى. ما بيتغير إلا \\(a,b,c,d\\) كلهم مضروبين بنفس العدد."),
