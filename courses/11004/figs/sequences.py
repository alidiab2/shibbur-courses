def Q(prompt, answer, hint, solution, options=None):
    q = {"kind": "mc" if options else "text", "prompt": "<p>%s</p>" % prompt}
    if options:
        q["options"] = [{"v": str(i + 1), "html": o} for i, o in enumerate(options)]
    q["answer"] = answer
    q["hint"] = "<p>%s</p>" % hint
    q["solution"] = "<p>%s</p>" % solution
    return {"t": "quiz", "q": q}


def hop(f, p0, p1, lift, c="2", w=3.5, **st):
    """arc from p0 to p1 bulging up by `lift`, with an arrow head at p1"""
    (x0, y0), (x1, y1) = p0, p1
    cx, cy = (x0 + x1) / 2, (y0 + y1) / 2 - lift * 2
    f.path("M%.1f,%.1f Q%.1f,%.1f %.1f,%.1f" % (x0, y0, cx, cy, x1, y1), c, "none", w, **st)
    t = 0.78
    bx = lambda a, b, d: (1 - t) ** 2 * a + 2 * (1 - t) * t * b + t * t * d
    f.arrow(bx(x0, cx, x1), bx(y0, cy, y1), x1, y1, c, w, **st)
    return ((x0 + x1) / 2, (y0 + y1) / 2 - lift)  # top of the arc


