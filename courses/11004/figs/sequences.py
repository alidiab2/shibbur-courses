blocks = []
blocks.append(WHY(
    "<p>المتتالية (<bdi>סדרה</bdi>) هي دالة عادية، بس مجالها الأعداد الطبيعية. كل الفصل الجاي (النهايات) عن المتتاليات، فلازم نعرفها منيح من هون.</p>"
    "<p><b>بهالدرس:</b></p><ol>"
    "<li>المتتالية كدالة من \\(\\mathbb{N}\\)</li>"
    "<li>متتالية حسابية (<bdi>סדרה חשבונית</bdi>)</li>"
    "<li>مجموع المتتالية الحسابية</li>"
    "<li>متتالية هندسية (<bdi>סדרה הנדסית</bdi>)</li>"
    "<li>مجموع المتتالية الهندسية</li>"
    "<li>متتالية بالتكرار (<bdi>נסיגה</bdi>) وفيبوناتشي</li></ol>"))

# ---- 1
blocks.append(H("1 · المتتالية هي دالة"))
blocks.append(P("المتتالية هي دالة مجالها \\(\\mathbb{N}=\\{1,2,3,\\dots\\}\\). المدخل هو رقم المكان \\(n\\)، والمخرج هو العدد اللي بالمكان هاد."))
f = Fig(480, 290, alt="نقاط (n, 1/n) للمتتالية الهارمونية والصورة على المحور العمودي")
p = f.axes((70, 20, 380, 225), xr=(0, 9), yr=(-0.1, 1.2), ticks=(1, 0.5), grid=True, ylabel="aₙ", xlabel="n")
for n in range(1, 9): p.point(n, 1 / n, None, "1", "ne", r=8, step=2)
for n in range(1, 9):
    px_, py_ = p.pt(0, 1 / n)
    f.dot(px_, py_, "good", 7, step=3)
blocks.append(f.block("", "steps", [
    "المحاور: \\(n\\) أفقي وقيمة المتتالية \\(a_n\\) عمودي.",
    "لكل \\(n\\) منحط نقطة \\((n,\\tfrac1n)\\). هاي المتتالية الهارمونية.",
    "الصورة هي القيم اللي طلعت على المحور العمودي: \\(1,\\tfrac12,\\tfrac13,\\dots\\)"], title="غراف المتتالية \\(a_n=\\tfrac1n\\)"))
blocks.append(BOX("def", "تعريف · <bdi>הגדרה 2.19</bdi>",
    "<p>لمجموعة \\(A\\subseteq\\mathbb{R}\\)، دالة \\(f:\\mathbb{N}\\to A\\) تسمى <b>סדרה</b>. بالأخص إذا \\(A\\subseteq\\mathbb{R}\\) هي <b>סדרת מספרים ממשיים</b>.</p>"
    "<p>الصورة \\(\\operatorname{Im}(f)=\\{f(1),f(2),f(3),\\dots\\}\\) منكتبها ببساطة \\(\\{f(n)\\}_{n=1}^{\\infty}\\).</p>"
    "<p>العادة نكتب \\(a_n=f(n)\\) والمتتالية \\(\\{a_n\\}_{n=1}^{\\infty}\\).</p>"))
blocks.append(BOX("ex", "مثال · <bdi>דוגמה 2.20</bdi>",
    "<p><b>הסדרה ההרמונית</b> معرفة بالدالة \\(h:\\mathbb{N}\\to\\mathbb{R}\\)، \\(h(n)=\\tfrac1n\\). نكتب \\(a_n=\\tfrac1n\\) أو باختصار \\(\\{\\tfrac1n\\}_{n=1}^{\\infty}\\).</p>"
    "<p>غرافها نقاط منفصلة كما بالرسم، وصورتها \\(\\{1,\\tfrac12,\\tfrac13,\\dots\\}\\).</p>"))
blocks.append(P("الكتاب بيطلب نتذكر مثالين من المدرسة: المتتالية الحسابية والمتتالية الهندسية. خلّينا نشوفهم."))

# ---- 2 arithmetic
blocks.append(H("2 · المتتالية الحسابية"))
blocks.append(P("بالمتتالية الحسابية كل عدد بيزيد على اللي قبله <b>نفس المقدار</b>. المقدار هاد اسمه الفرق (<bdi>הפרש</bdi>) ونرمز له \\(d\\). مثلاً \\(-3,5,13,21,\\dots\\) فيها \\(d=8\\)."))
f = Fig(480, 210, alt="خط أعداد: القفزات +8 من -3 إلى 5 إلى 13 إلى 21")
px = f.number_line(30, 450, 140, -5, 25, ticks=10)
vals = [-3, 5, 13, 21]
for k, v in enumerate(vals, start=1):
    f.dot(px(v), 140, "1", 11, step=k)
    f.text(px(v), 100, ["a₁", "a₂", "a₃", "a₄"][k - 1], "1", 22, 700, step=k)
for k in range(1, 4):
    f.arrow(px(vals[k - 1]) + 8, 70, px(vals[k]) - 8, 70, "2", 4, step=k + 1)
    f.text((px(vals[k - 1]) + px(vals[k])) / 2, 56, "+d", "2", 22, 700, step=k + 1)
blocks.append(f.block("", "steps", [
    "\\(a_1=-3\\) هو أول عدد.",
    "قفزة بمقدار \\(d=8\\): \\(a_2=-3+8=5\\).",
    "قفزة تانية: \\(a_3=5+8=13\\).",
    "وهيك لـ \\(a_4=21\\). كل مرة نفس القفزة."], title="كل قفزة بنفس الطول"))
blocks.append(BOX("def", "تعريف · <bdi>הגדרה 2.21</bdi>",
    "<p>متتالية \\(\\{a_n\\}_{n=1}^{\\infty}\\) تسمى <b>סדרה חשבונית</b> إذا يوجد عدد ثابت \\(d\\in\\mathbb{R}\\) (<bdi>ההפרש</bdi>) بحيث لكل \\(i\\in\\mathbb{N}\\) يتحقق\\[a_{i+1}-a_i=d.\\]</p>"
    "<p>عملياً، حدود المتتالية بتنكتب بدلالة \\(a_1\\) و \\(d\\). أول \\(n\\) حدود هم\\[a_1,\\ a_1+d,\\ a_1+2d,\\ \\dots,\\ a_1+(n-1)d.\\]</p>"))
blocks.append(TX("متتالية حسابية فيها \\(a_1=5\\) و \\(d=3\\). احسب \\(a_{10}\\).",
    ["32"], "الحد \\(n\\) هو \\(a_1+(n-1)d\\). كم قفزة بين \\(a_1\\) و \\(a_{10}\\)؟",
    "بين \\(a_1\\) و \\(a_{10}\\) في 9 قفزات. \\(a_{10}=5+9\\cdot3=32\\). الخطأ الشائع: ضرب 10 بدل 9."))

# ---- 3 arithmetic sum
blocks.append(H("3 · مجموع المتتالية الحسابية"))
blocks.append(P("بدنا نجمع أول \\(n\\) حدود. الحيلة: نجمع الأول مع الأخير، والتاني مع اللي قبل الأخير، وهيك. كل زوج إله <b>نفس المجموع</b>. شوف على \\(2,4,6,8,10,12\\)."))
f = Fig(480, 260, alt="الأعداد 2,4,6,8,10,12 مرتبة في أزواج مجموع كل زوج 14")
xs = [30 + 66 * i + 30 for i in range(6)]
for x, v in zip(xs, (2, 4, 6, 8, 10, 12)): f.chip(x - 30, 24, 60, 50, str(v), "1", size=24)
for k, (i, j, d, st) in enumerate([(0, 5, 120, 2), (1, 4, 84, 3), (2, 3, 48, 4)]):
    c = ["2", "good", "3"][k]
    y0 = 78
    f.path("M%s,%s L%s,%s L%s,%s L%s,%s" % (xs[i], y0, xs[i], y0 + d, xs[j], y0 + d, xs[j], y0), c, "none", 4, step=st)
    f.text((xs[i] + xs[j]) / 2, 78 + d - 10, "14", c, 24, 700, step=st)
f.chip(130, 212, 220, 40, "3 × 14 = 42", "good", solid=True, size=24, step=5, ltr=True)
blocks.append(f.block("", "steps", [
    "ستة حدود: \\(2,4,6,8,10,12\\).",
    "الأول مع الأخير: \\(2+12=14\\).",
    "التاني مع اللي قبل الأخير: \\(4+10=14\\). نفس المجموع.",
    "الأخيرين: \\(6+8=14\\). ثلاث أزواج كلها 14.",
    "المجموع: \\(3\\cdot14=42\\)، يعني \\(\\tfrac{2+12}{2}\\cdot 6\\)."], title="خدعة الأزواج"))
blocks.append(P("بالصيغة: مجموع كل زوج هو \\(a_1+a_n\\)، وعدد الأزواج \\(\\tfrac n2\\). لذلك المجموع هو \\(\\tfrac{a_1+a_n}{2}\\cdot n\\)."))
blocks.append(BOX("key", "صيغة · مجموع \\(n\\) حدود",
    "<p>لمتتالية حسابية فرقها \\(d\\):\\[S_n=a_1+a_2+\\dots+a_n\\]\\[=\\frac{a_1+a_n}{2}\\cdot n\\]\\[=\\frac{2a_1+d(n-1)}{2}\\cdot n.\\]</p>"))
blocks.append(BOX("ex", "مثال · <bdi>דוגמה 2.22</bdi>",
    "<p>المتتالية \\(\\{-3,5,13,21,\\dots\\}\\): \\(a_1=-3\\) و \\(d=8\\). مجموع أول 10 حدود:\\[S_{10}=\\frac{2\\cdot(-3)+8\\cdot9}{2}\\cdot10\\]\\[=\\frac{66}{2}\\cdot10=330.\\]</p>"))

# ---- 4 geometric
blocks.append(H("4 · المتتالية الهندسية"))
blocks.append(P("بالمتتالية الهندسية كل عدد هو اللي قبله <b>مضروب بنفس العدد</b>. العدد هاد اسمه المنسوب (<bdi>מנה</bdi>) ونرمز له \\(q\\). مثلاً \\(3,6,12,24,\\dots\\) فيها \\(q=2\\)."))
f = Fig(480, 170, alt="الأعداد 3 و6 و12 و24 وبينها أسهم ضرب في 2")
xs = [20 + 120 * i + 40 for i in range(4)]
for k, (x, v) in enumerate(zip(xs, (3, 6, 12, 24)), start=1):
    f.chip(x - 40, 80, 80, 56, str(v), "1", size=26, step=k)
for k in range(1, 4):
    f.arrow(xs[k - 1] + 14, 70, xs[k] - 14, 70, "2", 4, step=k + 1)
    f.text((xs[k - 1] + xs[k]) / 2, 50, "×2", "2", 24, 700, step=k + 1)
blocks.append(f.block("", "steps", [
    "\\(a_1=3\\).", "نضرب بـ \\(q=2\\): \\(a_2=6\\).", "نضرب مرة تانية: \\(a_3=12\\).", "ومرة: \\(a_4=24\\)."], title="كل خطوة ×q"))
blocks.append(BOX("def", "تعريف · <bdi>הגדרה 2.23</bdi>",
    "<p>متتالية \\(\\{a_n\\}_{n=1}^{\\infty}\\) تسمى <b>סדרה הנדסית</b> إذا يوجد عدد ثابت \\(q\\in\\mathbb{R}\\) (<bdi>המנה</bdi>) بحيث لكل \\(n\\in\\mathbb{N}\\) يتحقق \\(a_n=a_1q^{n-1}\\).</p>"
    "<p>عملياً، أول \\(n\\) حدود هم\\[a_1,\\ a_1q,\\ a_1q^2,\\ \\dots,\\ a_1q^{n-1}.\\]</p>"))

# ---- 5 geometric sum
blocks.append(H("5 · مجموع المتتالية الهندسية"))
blocks.append(P("لمتتالية هندسية <b>غير ثابتة</b> (يعني \\(q\\ne1\\)) في صيغة جاهزة لمجموع أول \\(n\\) حدود."))
blocks.append(BOX("key", "صيغة · مجموع \\(n\\) حدود",
    "<p>لمتتالية هندسية منسوبها \\(q\\ne1\\):\\[S_n=a_1+a_2+\\dots+a_n\\]\\[=a_1\\,\\frac{1-q^n}{1-q}.\\]</p>"))
blocks.append(P("تحقق سريع على \\(1,2,4\\) (\\(a_1=1,\\ q=2,\\ n=3\\)): الصيغة بتعطي \\(\\tfrac{1-8}{1-2}=7\\) وفعلاً \\(1+2+4=7\\)."))
blocks.append(BOX("ex", "مثال · <bdi>דוגמה 2.24</bdi>",
    "<p>احسب مجموع أول 10 حدود بمتتالية هندسية فيها \\(a_1=3\\) و \\(q=2\\):\\[S_{10}=3\\cdot\\frac{1-2^{10}}{1-2}\\]\\[=3(2^{10}-1).\\]</p>"))
blocks.append(MC("متتالية هندسية \\(a_1=2\\) و \\(q=3\\). كم \\(S_4\\)؟",
    ["\\(80\\)", "\\(54\\)", "\\(26\\)"], 1,
    "طبّق \\(a_1\\frac{1-q^n}{1-q}\\) مع \\(n=4\\). أو اجمع الحدود: \\(2,6,18,54\\).",
    "\\(S_4=2\\cdot\\frac{1-81}{1-3}=2\\cdot40=80\\). \\(54\\) هو الحد الرابع لحاله، و \\(26\\) هو مجموع ثلاثة حدود فقط."))

# ---- 6 recursion
blocks.append(H("6 · متتالية بالتكرار"))
blocks.append(P("في طريقة تانية نعرّف متتالية: بدل صيغة لـ \\(a_n\\)، منعطي <b>قاعدة</b> بتحسب الحد الجاي من الحدود اللي قبله. هاي متتالية معرفة بـ <b>נסיגה</b> (برקורסיה)."))
blocks.append(BOX("note", "رسمياً · <bdi>נסיגה</bdi>",
    "<p>بعطاء أول \\(n\\) حدود لمتتالية \\(\\{a_n\\}_{n=1}^{\\infty}\\)، الحد الجاي بيتحدد بقاعدة\\[a_{n+1}=f(a_1,a_2,\\dots,a_n)\\]وهيك للحد بعده، وهكذا.</p>"))
f = Fig(480, 230, alt="فيبوناتشي: 1 و2 ثم كل حد مجموع الحدين قبله: 3 و5 و8 و13")
xs = [30 + 72 * i + 30 for i in range(6)]
vals = (1, 2, 3, 5, 8, 13)
for k, (x, v) in enumerate(zip(xs, vals)):
    f.chip(x - 30, 120, 60, 54, str(v), "1" if k < 2 else "good", size=26, step=1 if k < 2 else k)
for k in range(2, 6):
    for src in (k - 2, k - 1):
        f.path("M%s,118 Q%s,%s %s,118" % (xs[src], (xs[src] + xs[k]) / 2, 40 + 10 * (k - src), xs[k]), "2", "none", 3.5, step=k, until=k)
    f.text(xs[k], 198, "%d + %d" % (vals[k - 2], vals[k - 1]), "2", 20, 700, step=k, until=k)
blocks.append(f.block("", "steps", [
    "نبدأ بحدين معطيين: \\(a_1=1\\) و \\(a_2=2\\).",
    "\\(a_3=a_1+a_2=1+2=3\\).",
    "\\(a_4=a_2+a_3=2+3=5\\).",
    "\\(a_5=a_3+a_4=3+5=8\\).",
    "\\(a_6=a_4+a_5=5+8=13\\)."], title="كل حد = مجموع اللي قبله"))
blocks.append(BOX("ex", "مثال · <bdi>דוגמה 2.25</bdi>",
    "<p><b>סדרת פיבונאצ'י</b> معرفة بالقاعدة\\[a_{n+2}=a_n+a_{n+1}.\\]مع \\(a_1,a_2\\) معطيين. مثلاً \\(a_1=1,\\ a_2=2\\) بتعطي \\(\\{1,2,3,5,8,13,\\dots\\}\\).</p>"
    "<p>هاي المتتالية بتجاوب على لغز الدرج: بكم طريقة نطلع \\(n\\) درجات إذا كل مرة بنطلع درجة أو درجتين؟</p>"))
blocks.append(TX("فيبوناتشي مع \\(a_1=1,\\ a_2=2\\). كم \\(a_7\\)؟",
    ["21"], "كمّل بعد \\(13\\): \\(a_7=a_5+a_6\\).",
    "\\(a_5=8\\)، \\(a_6=13\\). فـ \\(a_7=8+13=21\\)."))

blocks.append(MISTAKES("أخطاء شائعة", [
    ("\\(a_n=a_1+nd\\)", "\\(a_n=a_1+(n-1)d\\) (أول حد ما فيه قفزة)"),
    ("\\(a_n=a_1q^{n}\\)", "\\(a_n=a_1q^{n-1}\\)"),
    ("صيغة مجموع الهندسية مع \\(q=1\\)", "الصيغة بتحتاج \\(q\\ne1\\) (لأنه \\(1-q\\) بالمقام)"),
    ("فيبوناتشي: \\(a_{n+2}=a_{n+1}+1\\)", "\\(a_{n+2}=a_n+a_{n+1}\\) (مجموع حدين)"),
]))
blocks.append(CHECK([
    "סדרה = دالة \\(f:\\mathbb{N}\\to A\\) و \\(a_n=f(n)\\)، \\(\\{a_n\\}_{n=1}^\\infty\\).",
    "סדרה הרמונית \\(a_n=\\tfrac1n\\).",
    "סדרה חשבונית: \\(a_{i+1}-a_i=d\\) و \\(S_n=\\tfrac{a_1+a_n}{2}n\\).",
    "סדרה הנדסית: \\(a_n=a_1q^{n-1}\\) و \\(S_n=a_1\\tfrac{1-q^n}{1-q}\\).",
    "נסיגה: \\(a_{n+1}=f(a_1,\\dots,a_n)\\)، فיבונאצ'י \\(a_{n+2}=a_n+a_{n+1}\\)."]))
blocks.append(CARD("مجموع حسابية (<bdi>סדרה חשבונית</bdi>)", "\\(S_n=\\dfrac{a_1+a_n}{2}\\cdot n=\\dfrac{2a_1+d(n-1)}{2}\\cdot n\\)"))
blocks.append(CARD("مجموع هندسية (<bdi>סדרה הנדסית</bdi>)", "\\(S_n=a_1\\dfrac{1-q^n}{1-q}\\)، \\(q\\ne1\\)"))
blocks.append(CARD("فيبوناتشي", "\\(a_{n+2}=a_n+a_{n+1}\\)"))
blocks.append(TX("احسب \\(1+2+3+\\dots+100\\).", ["5050"],
    "متتالية حسابية: \\(a_1=1\\)، \\(d=1\\)، \\(n=100\\).",
    "\\(S_{100}=\\frac{1+100}{2}\\cdot100=5050\\)."))
blocks.append(MC("المتتالية \\(7,4,1,-2,\\dots\\) هي:",
    ["هندسية \\(q=-\\tfrac{4}{7}\\)", "حسابية \\(d=-3\\)", "حسابية \\(d=3\\)"], 2,
    "احسب \\(a_2-a_1\\) و \\(a_3-a_2\\). هل هم نفس العدد؟",
    "\\(4-7=-3\\)، \\(1-4=-3\\)، \\(-2-1=-3\\). الفرق ثابت \\(-3\\): حسابية. النسبة \\(\\tfrac47\\) و \\(\\tfrac14\\) مش ثابتة."))
blocks.append(TX("حسابية فيها \\(a_1=-3\\) و \\(d=8\\). كم \\(S_5\\)؟", ["65"],
    "اكتب الحدود: \\(-3,5,13,21,29\\) واجمع، أو استعمل الصيغة.",
    "\\(S_5=\\frac{2(-3)+8\\cdot4}{2}\\cdot5=\\frac{26}{2}\\cdot5=65\\). ونتأكد: \\(-3+5+13+21+29=65\\)."))
write_lesson("sequences", "المتتاليات: حسابية وهندسية وبالتكرار", "סדרות", "חוברת §2.1 · עמ׳ 11–13", "المتتالية كدالة من الأعداد الطبيعية، الحسابية والهندسية ومجاميعها، وفيبوناتشي.", blocks)
