def hfull(p, y, c="mut", dash=True, step=None, only=None, until=None):
    bx, by, bw, bh = p.box
    py = p.pt(0, y)[1]
    return p.f.line(bx, py, bx + bw, py, c, 3, dash, step=step, only=only, until=until)


def roots(fn, y, lo, hi, n=3000):
    out, xs = [], [lo + (hi - lo) * i / n for i in range(n + 1)]
    for a, b in zip(xs, xs[1:]):
        fa, fb = fn(a) - y, fn(b) - y
        if fa == 0: out.append(a)
        elif fa * fb < 0:
            for _ in range(50):
                m = (a + b) / 2
                if (fn(a) - y) * (fn(m) - y) <= 0: b = m
                else: a = m
            out.append((a + b) / 2)
    return out


